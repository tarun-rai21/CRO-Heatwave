"""Baseline report (reports/baselines.md) and gate G2 (reference.md §3.7)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from heatwave.validation import metrics


def _md(df: pd.DataFrame, nd: int = 3) -> str:
    if df.empty:
        return "_none_\n"
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].round(nd)
    head = "| " + " | ".join(map(str, d.columns)) + " |\n|" + "---|" * len(d.columns) + "\n"
    return (
        head
        + "\n".join(
            "| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |"
            for r in d.itertuples(index=False)
        )
        + "\n"
    )


def _wide(t: pd.DataFrame, group_name: str) -> pd.DataFrame:
    """One row per group: 'model: bss [lo, hi]' per model."""
    t = t.assign(
        cell=lambda x: x.apply(lambda r: f"{r.bss:+.3f} [{r.lo:+.3f}, {r.hi:+.3f}]", axis=1)
    )
    w = t.pivot(index="group", columns="model", values="cell").reset_index()
    rows = t.groupby("group")["rows"].first()
    w.insert(1, "rows", w["group"].map(rows))
    return w.rename(columns={"group": group_name})


def skill_horizon(t: pd.DataFrame, model: str) -> int | None:
    """Last lead before the first one whose interval includes 0 (None if lead 1 already does)."""
    s = t[t["model"] == model].sort_values("group")
    last = None
    for r in s.itertuples():
        if r.lo <= 0:
            return last
        last = int(r.group)
    return last


def build(
    lead_oof: pd.DataFrame,
    window_oof: pd.DataFrame,
    cfg: dict,
    out: Path,
    coefficients: pd.DataFrame | None = None,
) -> dict:
    e = cfg["evaluation"]
    nb, seed, ci = e["bootstrap_resamples"], e["bootstrap_seed"], e["ci"]
    models, pairs = ["M1", "M2"], [("M2", "M1"), ("M1", "M0"), ("M2", "M0")]

    lead_all = metrics.bss_table(lead_oof, models, "M0", "lead", nb, seed, ci, pairs)
    lead_onset = metrics.bss_table(
        lead_oof[lead_oof["onset"]], models, "M0", "lead", nb, seed, ci, pairs
    )
    win_all = metrics.bss_table(window_oof, models, "M0", None, nb, seed, ci, pairs)
    win_onset = metrics.bss_table(
        window_oof[window_oof["onset"]], models, "M0", None, nb, seed, ci, pairs
    )
    by_month = metrics.bss_table(lead_oof, models, "M0", "month", nb, seed, ci)
    by_region = metrics.bss_table(lead_oof, models, "M0", "region", nb, seed, ci)
    by_year = (
        lead_oof.groupby("year")
        .apply(
            lambda g: pd.Series(
                {
                    "rows": len(g),
                    "base_rate": g["y"].mean(),
                    **{
                        f"BSS_{m}": 1
                        - ((g[f"p_{m}"] - g["y"]) ** 2).sum() / ((g["p_M0"] - g["y"]) ** 2).sum()
                        for m in models
                    },
                }
            )
        )
        .reset_index()
    )
    disc = metrics.discrimination(lead_oof, ["M0", "M1", "M2"], "lead")
    disc_w = metrics.discrimination(window_oof, ["M0", "M1", "M2"], None)
    rel = {m: metrics.reliability(lead_oof, m, e["reliability_bins"]) for m in ["M0", "M2"]}
    dec = pd.DataFrame(
        [
            {"model": m, **metrics.brier_decomposition(lead_oof, m, e["reliability_bins"])}
            for m in ["M0", "M1", "M2"]
        ]
    )

    # Gate G2: sensible skill-by-lead curves for M1 and M2.
    floor = e["g2"]["min_bss_lead1"]
    checks = {}
    for m in models:
        s = lead_all[lead_all["model"] == m].set_index("group")
        checks[f"{m}: lead-1 interval above {floor}"] = bool(s.loc[1, "lo"] > floor)
        checks[f"{m}: skill falls from lead 1 to lead 10"] = bool(
            s.loc[1, "bss"] > s.loc[10, "bss"]
        )
    folds = pd.DataFrame(lead_oof.attrs.get("fold_checks", []))
    if not folds.empty:
        worst = float((folds["m0_train_mean"] / folds["train_rate"] - 1).abs().max())
        checks["M0 matches its training-row rate in every fold (within 2 %)"] = bool(worst < 0.02)
    g2 = all(checks.values())
    horizon = {k: skill_horizon(t, "M2") for k, t in [("all", lead_all), ("onset", lead_onset)]}

    years = sorted(lead_oof["year"].unique())
    check_tab = pd.DataFrame(
        {"check": list(checks), "result": ["pass" if v else "FAIL" for v in checks.values()]}
    )
    base = disc.groupby("group")["base_rate"].first().rename("base_rate")
    pr_tab = (
        disc.pivot(index="group", columns="model", values="pr_auc")
        .join(base)
        .reset_index()
        .rename(columns={"group": "lead"})
    )
    roc_tab = (
        disc.pivot(index="group", columns="model", values="roc_auc")
        .reset_index()
        .rename(columns={"group": "lead"})
    )
    text = f"""# Baselines (gate G2)

Generated by `uv run heatwave evaluate-baselines`.
Decisions: `docs/decisions/008-phase6-baselines.md`.

- Out-of-fold predictions from the 5 walk-forward folds: validation years {years[0]}-{years[-1]}
  ({len(years)} years). Each fold's models and climatology use only its training years.
- Scored rows: valid dates in the evaluation season (March-July). Window target: all ten
  valid dates in the season.
- BSS = 1 - BS / BS(M0); intervals: {ci:.0%} year-block bootstrap ({nb} resamples of whole
  years, all districts together). Model differences are paired (same resampled years).
- M0 climatology; M1 persistence lookup; M2 logistic regression (one model per lead).
- Onset subset: no heatwave day in the 3 days up to the as-of date.

**Gate G2: {"PASS" if g2 else "FAIL"}**

{_md(check_tab)}
Climatology in and out of sample, per fold (information, not a check: out-of-sample
years can be hotter or cooler than the training years):

{_md(folds, 4)}
**Skill horizon (M2 vs climatology):** last lead whose interval excludes 0:
all issue dates **{horizon["all"]}**; onset subset **{horizon["onset"]}**.

## 1. Per-lead target, all issue dates: BSS [interval]

{_md(_wide(lead_all, "lead"))}
## 2. Per-lead target, onset subset: BSS [interval]

{_md(_wide(lead_onset, "lead"))}
## 3. Window target (any heatwave in the next 10 days)

All issue dates:

{_md(_wide(win_all.assign(group="window"), "target"))}
Onset subset:

{_md(_wide(win_onset.assign(group="window"), "target"))}
## 4. Discrimination (per-lead; base rate and M0 beside every value)

{_md(pr_tab)}
PR-AUC above. ROC-AUC:

{_md(roc_tab)}
Window target:

{_md(disc_w.drop(columns=["group"]))}
## 5. Calibration (per-lead, all leads pooled)

Brier decomposition (BS ~ reliability - resolution + uncertainty):

{_md(dec, 5)}
Reliability, M2 (equal-count bins):

{_md(rel["M2"])}
Reliability, M0:

{_md(rel["M0"])}
## 6. By valid month (per-lead, all leads)

{_md(_wide(by_month, "month"))}
## 7. By region (per-lead, all leads)

{_md(_wide(by_region, "region"))}
## 8. By year (per-lead, all leads; point estimates)

{_md(by_year)}"""
    if coefficients is not None:
        text += f"""
## 9. M2 coefficients (fold 5, standardised inputs)

{_md(coefficients)}"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return {
        "g2": g2,
        "checks": checks,
        "skill_horizon": horizon,
        "lead1": lead_all[lead_all["group"] == 1][["model", "bss", "lo", "hi"]]
        .round(3)
        .to_dict("records"),
        "lead10": lead_all[lead_all["group"] == 10][["model", "bss", "lo", "hi"]]
        .round(3)
        .to_dict("records"),
        "window": win_all[["model", "bss", "lo", "hi"]].round(3).to_dict("records"),
    }
