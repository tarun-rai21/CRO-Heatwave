"""Full-history QA report (reports/data_qa.md) and the daily validate step."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd

from heatwave.ingest.raw_store import RawStore
from heatwave.ingest.run import Paths, check_spine
from heatwave.quality import checks


def _md_table(df: pd.DataFrame) -> str:
    if df.empty:
        return "_none_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines) + "\n"


def build_report(data_cfg: dict, quality_cfg: dict, paths: Paths, out: Path) -> dict:
    """Run every check over the full history and write the markdown report.
    Returns a summary; summary['ok'] is False on any hard failure or unreviewed flag."""
    from heatwave.ingest.imd import ImdSettings

    variables = list(quality_cfg["hard"]["ranges"])
    if set(variables) != set(data_cfg["power"]["parameters"]):
        raise ValueError("configs/quality.yaml ranges must cover exactly the POWER parameters")

    start = date.fromisoformat(data_cfg["power"]["start"])
    spine = check_spine(paths, start, data_cfg["power"]["parameters"])
    wide = checks.load_wide(RawStore(paths.raw_power), variables)
    cells = pd.read_parquet(paths.grid_cells)

    hard = checks.hard_failures(wide, quality_cfg["hard"])
    flags = checks.mark_reviewed(
        checks.soft_flags(wide, cells, quality_cfg["soft"]), quality_cfg.get("reviewed_flags")
    )
    unreviewed = flags[flags["reason"].isna()]
    nulls = checks.null_rates(wide, variables)

    imd_cfg = data_cfg["imd"]
    imd_years = sorted(int(p.stem) for p in (paths.root / imd_cfg["raw_dir"]).glob("*.GRD"))
    imd = checks.imd_checks(
        ImdSettings.from_config(imd_cfg),
        paths.root / imd_cfg["raw_dir"],
        imd_years,
        quality_cfg["imd"]["up_bbox"],
        quality_cfg["imd"]["tmax_range"],
    )

    ranges = wide[variables].agg(["min", "max"]).T.round(2).reset_index(names="variable")
    ok = spine["complete"] and hard.empty and unreviewed.empty and imd["out_of_range"].sum() == 0
    in_season = flags["obs_date"].dt.month.between(3, 6)
    soft = quality_cfg["soft"]
    jump, spatial = soft["jump"], soft["spatial"]
    last_day = min(spine["last_date_by_variable"].values())
    n_vars = len(data_cfg["power"]["parameters"])
    flag_table = flags.assign(
        obs_date=flags["obs_date"].dt.date.astype(str), value=flags["value"].round(2)
    )
    null_text = (
        "No missing values in any variable or year."
        if not nulls.to_numpy().any()
        else _md_table(nulls.round(4).reset_index(names="year"))
    )
    imd_missing, imd_bad = int(imd["missing"].sum()), int(imd["out_of_range"].sum())

    text = f"""# Data quality report

Generated by `uv run heatwave qa-report` from the raw store's best-known values.
Rules: `configs/quality.yaml`.
Decisions and explanations: `docs/decisions/004-phase3-data-quality.md`.

**Overall: {"PASS" if ok else "FAIL"}**

## 1. NASA POWER completeness

- Cells: {spine["cells"]}; period {spine["first_date"]} to {last_day}
- Values (best-known): {spine["rows"]:,} across {n_vars} variables
- Complete date spine for every cell and variable: **{spine["complete"]}**
- Missing values: {spine["null_values_by_variable"] or "none"}

## 2. Hard checks (physically impossible values)

Ranges, Tmin <= Tmean <= Tmax, dew point <= Tmean, unique (cell, date).
Violations: **{len(hard)}**

{_md_table(hard.head(50))}
Observed range per variable:

{_md_table(ranges)}
## 3. Soft flags (suspicious but possible; kept, never altered)

- Isolated day-to-day jumps: robust z > {jump["z"]} with no neighbour moving by
  z > {jump["neighbour_z"]}; variables {", ".join(jump["variables"])}
- Spatial outliers: more than {spatial["abs_dev_c"]} C from the neighbours' median
  beyond the usual offset; variables {", ".join(spatial["variables"])}

Flags: **{len(flags)}** ({int(in_season.sum())} in March-June);
reviewed {len(flags) - len(unreviewed)}, **unreviewed {len(unreviewed)}**.

{_md_table(flag_table)}
## 4. Missing values by year

{null_text}

## 5. IMD gridded Tmax over UP (box {quality_cfg["imd"]["up_bbox"]})

Years present: {imd_years[0]}-{imd_years[-1]} ({len(imd_years)}).
Missing point-days: {imd_missing}; out-of-range values: {imd_bad}.

{_md_table(imd)}"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return {
        "ok": bool(ok),
        "spine_complete": spine["complete"],
        "hard_failures": len(hard),
        "soft_flags": len(flags),
        "unreviewed_flags": len(unreviewed),
        "imd_out_of_range": int(imd["out_of_range"].sum()),
        "report": str(out),
    }


def validate_recent(data_cfg: dict, quality_cfg: dict, paths: Paths, today: date) -> dict:
    """Daily gate: hard checks on the current (and, early in the year, previous)
    observation year, every cell present on the newest day, and latency."""
    variables = list(quality_cfg["hard"]["ranges"])
    years = sorted({today.year, (pd.Timestamp(today) - pd.Timedelta(days=120)).year})
    wide = checks.load_wide(RawStore(paths.raw_power), variables, years)
    cells = set(pd.read_parquet(paths.grid_cells)["cell_id"])

    hard = checks.hard_failures(wide, quality_cfg["hard"])
    newest = wide["obs_date"].max()
    complete_on_newest = wide.loc[wide["obs_date"] == newest].dropna(subset=variables)
    missing_cells = sorted(cells - set(complete_on_newest["cell_id"]))
    latency = (pd.Timestamp(today) - newest).days
    max_latency = quality_cfg["hard"]["max_latency_days"]

    problems = []
    if not hard.empty:
        problems.append(f"{len(hard)} hard-check violations")
    if missing_cells:
        problems.append(f"{len(missing_cells)} cells incomplete on {newest.date()}")
    if latency > max_latency:
        problems.append(f"newest data {newest.date()} is {latency} days old (limit {max_latency})")
    return {
        "ok": not problems,
        "problems": problems,
        "newest_date": str(newest.date()),
        "latency_days": latency,
        "hard_failures": hard.head(20).to_dict("records"),
        "missing_cells": missing_cells[:20],
    }
